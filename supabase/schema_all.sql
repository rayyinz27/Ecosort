drop policy if exists "scan_own_insert" on public.scan_history;
create policy "scan_own_select" on public.scan_history for select to authenticated using (user_id = auth.uid() or public.is_admin());
create policy "scan_own_insert" on public.scan_history for insert to authenticated with check (user_id = auth.uid());

drop policy if exists "quiz_own_select" on public.quiz_results;
drop policy if exists "quiz_own_insert" on public.quiz_results;
create policy "quiz_own_select" on public.quiz_results for select to authenticated using (user_id = auth.uid() or public.is_admin());
create policy "quiz_own_insert" on public.quiz_results for insert to authenticated with check (user_id = auth.uid());

