-- ===== 2. schema_update.sql (role admin + policy) =====
-- EcoSort: update skema untuk login user/admin + kelola konten.
-- Jalankan SETELAH schema.sql, di Supabase → SQL Editor. Aman dijalankan berulang.

-- 1) Kolom peran pada profil
alter table public.profiles add column if not exists role text not null default 'user';
alter table public.profiles drop constraint if exists profiles_role_check;
alter table public.profiles add constraint profiles_role_check check (role in ('user','admin'));

-- 2) Fungsi bantu (security definer agar policy tidak rekursif)
create or replace function public.my_role() returns text
language sql security definer set search_path = public stable
as $$ select role from public.profiles where id = auth.uid() $$;

create or replace function public.is_admin() returns boolean
language sql security definer set search_path = public stable
as $$ select coalesce((select role = 'admin' from public.profiles where id = auth.uid()), false) $$;

-- 3) Buat profil otomatis saat user mendaftar (selalu role 'user')
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (new.id, new.raw_user_meta_data->>'full_name', 'user')
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- 4) Policy: profiles
drop policy if exists "profiles_select" on public.profiles;
drop policy if exists "profiles_insert" on public.profiles;
drop policy if exists "profiles_update" on public.profiles;
create policy "profiles_select" on public.profiles for select to authenticated
  using (id = auth.uid() or public.is_admin());
create policy "profiles_insert" on public.profiles for insert to authenticated
  with check (id = auth.uid() and role = 'user');
-- user boleh ubah profilnya sendiri tetapi TIDAK boleh mengubah role
create policy "profiles_update" on public.profiles for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid() and role = public.my_role());

-- 5) Konten publik: semua orang boleh baca, hanya admin yang boleh tulis
do $$
declare t text;
begin
  foreach t in array array['waste_categories','waste_catalog','waste_banks','organizations','environmental_events','tutorials','quiz_questions']
  loop
    execute format('drop policy if exists "%1$s_read" on public.%1$s', t);
    execute format('drop policy if exists "%1$s_admin_write" on public.%1$s', t);
    execute format('create policy "%1$s_read" on public.%1$s for select to anon, authenticated using (true)', t);
    execute format('create policy "%1$s_admin_write" on public.%1$s for all to authenticated using (public.is_admin()) with check (public.is_admin())', t);
  end loop;
end $$;

-- 6) Data milik user: riwayat scan & hasil kuis
