// Ubah string base64 menjadi bytes (untuk upload foto ke Supabase Storage)
const CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
const LOOKUP: Record<string, number> = {};
for (let i = 0; i < CHARS.length; i++) LOOKUP[CHARS[i]] = i;

export function b64ToBytes(b64: string): Uint8Array {
  const clean = b64.replace(/[^A-Za-z0-9+/]/g, '');
  const len = clean.length;
  const out = new Uint8Array(Math.floor((len * 3) / 4));
  let p = 0;
  for (let i = 0; i < len; i += 4) {
    const a = LOOKUP[clean[i]], b = LOOKUP[clean[i + 1]];
    const c = i + 2 < len ? LOOKUP[clean[i + 2]] : 0;
    const d = i + 3 < len ? LOOKUP[clean[i + 3]] : 0;
    out[p++] = (a << 2) | (b >> 4);
    if (i + 2 < len) out[p++] = ((b & 15) << 4) | (c >> 2);
    if (i + 3 < len) out[p++] = ((c & 3) << 6) | d;
  }
  return out.slice(0, p);
}
